// API real descartável; nunca executar no banco operacional.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const api = process.env.EXPIRED_REFILL_TEST_API;
if (!api || api === 'http://localhost:8080') throw Error('Informe uma API descartável em EXPIRED_REFILL_TEST_API.');
const { _electron } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const username = `expired${Date.now()}`, password = randomUUID();
let headers = { 'Content-Type': 'application/json' };
async function request(method, path, body) {
  const response = await fetch(`${api}${path}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
  assert.ok(response.ok, `${method} ${path}: ${response.status} ${response.ok ? '' : await response.text()}`);
  return response.status === 204 ? undefined : response.json();
}
await request('POST', '/users', { firstName: 'Teste', username, email: `${username}@example.com`, password, userRole: 'ADMIN' });
headers.Authorization = `Basic ${Buffer.from(`${username}:${password}`).toString('base64')}`;
const client = await request('POST', '/clients', { name: `Cliente ${username}`, clientType: 'RETAIL', clientStatus: 'PAID' });
const water = await request('POST', '/products', { name: `Agua ${username}`, type: 'WATER', basePrice: 9 });
const expired = await request('POST', '/products', { name: `Vencido ${username}`, type: 'EXPIRED_BOTTLE', basePrice: 3 });
await request('PATCH', `/stocks/products/${water.id}`, 5);
const initialFilled = (await request('GET', '/bottle-inventory')).filledQuantity;
const validQuantity = initialFilled + 20;
await request('PUT', '/bottle-inventory', { validQuantity, expiredQuantity: 3 });
const profile = await mkdtemp(join(tmpdir(), 'vitalis-expired-'));
const app = await _electron.launch({ executablePath: createRequire(import.meta.url)('electron'), args: ['.', `--user-data-dir=${profile}`], env: { ...process.env, VITE_DEV_SERVER_URL: 'http://localhost:5173' } });
const page = await app.firstWindow();
await page.route('http://localhost:8080/**', route => route.continue({ url: route.request().url().replace('http://localhost:8080', api) }));
page.setDefaultTimeout(15000);
try {
  await page.goto('http://localhost:5173/#/login');
  await page.locator('#username').fill(username);
  await page.locator('#password').fill(password);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.waitForURL('**/#/dashboard');
  await page.goto('http://localhost:5173/#/products');
  await page.getByRole('button', { name: /Novo Produto/ }).click();
  await page.locator('form').getByRole('button', { name: /Garrafão vencido/ }).click();
  assert.equal(await page.getByText('Vasilhame vencido, vendido sem água.', { exact: false }).count(), 0);
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.goto('http://localhost:5173/#/orders');
  await page.getByRole('button', { name: /Novo Pedido/ }).click();
  await page.getByPlaceholder('Buscar cliente...').fill(client.name);
  await page.getByRole('button').filter({ has: page.getByText(client.name, { exact: true }) }).click();
  await page.locator('form tbody select').first().selectOption(expired.id);
  assert.equal(await page.getByText('Vencido, sem água.', { exact: true }).count(), 0);
  await page.getByLabel('Operação com garrafão vencido', { exact: true }).selectOption('REFILL');
  const waterSelect = page.getByLabel('Água da troca no item 1', { exact: true });
  assert.equal(await waterSelect.evaluate(el => el.checkValidity()), false);
  await waterSelect.selectOption(water.id);
  const responsePromise = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/orders'));
  await page.getByRole('button', { name: /Salvar Pedido/ }).click();
  const response = await responsePromise;
  assert.equal(response.status(), 201);
  assert.equal(response.request().postDataJSON().items[0].bottleMode, 'REFILL');
  const order = (await response.json())[0];
  await page.goto(`http://localhost:5173/#/orders/${order.id}`);
  await page.getByRole('button', { name: /Editar/ }).click();
  assert.equal(await page.getByLabel('Operação com garrafão vencido', { exact: true }).inputValue(), 'REFILL');
  assert.equal(await page.getByLabel('Água da troca no item 1', { exact: true }).inputValue(), water.id);
  await page.getByRole('button', { name: /Salvar/ }).click();
  await page.getByRole('heading', { name: /Editar Pedido/i }).waitFor({ state: 'hidden' });
  await request('PATCH', `/orders/${order.id}/confirm-delivery`);
  let inventory = await request('GET', '/bottle-inventory');
  assert.equal(inventory.validQuantity, validQuantity); assert.equal(inventory.expiredQuantity, 3); assert.equal(inventory.filledQuantity, initialFilled - 1);
  await page.reload();
  await page.getByRole('button', { name: /Editar/ }).click();
  await page.getByLabel('Operação com garrafão vencido', { exact: true }).selectOption('EXPIRED');
  await page.getByRole('button', { name: 'Salvar correção', exact: true }).click();
  await page.getByRole('heading', { name: 'Editar pedido concluído', exact: true }).waitFor({ state: 'hidden' });
  inventory = await request('GET', '/bottle-inventory');
  assert.equal(inventory.expiredQuantity, 2); assert.equal(inventory.filledQuantity, initialFilled);
  await request('DELETE', `/orders/${order.id}`);
  inventory = await request('GET', '/bottle-inventory');
  assert.equal(inventory.expiredQuantity, 3); assert.equal(inventory.filledQuantity, initialFilled);
  console.log('PASS Electron: textos removidos, criação/edição da troca, entrega preserva vasilhames, correção para venda e cancelamento.');
} finally { await app.close(); }
